// node "LA BASE DE SKY/Plugins/MakerStudio/003_Editor/Mods/Battle Animation Studio/tests/performance_preflight.test.mjs"
import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
const src=await readFile(new URL("../performance_preflight.js",import.meta.url),"utf8");
const {preflightBasAnimation,preflightBasProject}=await import("data:text/javascript;base64,"+Buffer.from(src).toString("base64"));
const emitter=(rate,intensity,life=10,end=60)=>({id:"e1",name:"Impact",startFrame:0,endFrame:end,positionKeys:[{point:{anchor:"target_battler"}}],pbs:{emitter:"Straight",emitterRate:rate,emitterIntensity:intensity,simpleParticleLife:{duration:life},emitterCommands:{emitting:[{frame:0,value:true},{frame:end-1,value:false}]}}});
const anim=(clip,source={})=>({id:"a",duration:80,fps:20,source,tracks:[{clips:[clip]}]});
const light=anim(emitter(1,1,3));
const before=JSON.stringify(light);
const small=preflightBasAnimation(light);
assert(small.worst.peak<240);
assert.equal(JSON.stringify(light),before);
const heavy=anim(emitter(10000,3,30),{targetScope:"all_battlers",autoReplicateAffected:true});
const report=preflightBasAnimation(heavy);
assert(report.worst.peak>240);
assert(report.scenarios[2].peak>report.scenarios[0].peak);
assert(report.issues.some(x=>x.code==="PARTICLE_OVER_BUDGET"));
assert.equal(report.scenarios.length,3);
const compact=preflightBasProject({animations:[light,heavy]});
assert.equal(compact.animations.length,2);
assert.equal(compact.warnings,1);
const empty=preflightBasProject({animations:[]});
assert.equal(empty.animations.length,0);
console.log("BAS predictive performance preflight tests passed");
