export const FX_LIMIT=128;
const clamp=(v,a,b)=>Math.max(a,Math.min(b,v));
export function fxParticle(c,i,elapsed){
 const count=clamp(Math.round(Number(c.count)||1),1,48),cycle=Math.max(1,Number(c.cycle)||60),phase=((elapsed+i*cycle/count)%cycle+cycle)%cycle/cycle,angle=i*2.399963229728653+phase*Math.PI*2;
 const rx=Number(c.rangeX)||0,ry=Number(c.rangeY)||0,sway=Number(c.sway)||0;let x=0,y=0;
 switch(c.pattern){
 case "orbit":x=Math.cos(angle)*rx;y=Math.sin(angle)*ry*.45;break;
 case "vortex":x=Math.cos(angle)*rx*(1-phase);y=ry*.5-phase*ry;break;
 case "rain":x=Math.sin(i*2.399963)*rx;y=-ry+phase*ry*2;break;
 case "burst":x=Math.cos(i*2.399963)*rx*phase;y=Math.sin(i*2.399963)*ry*phase;break;
 case "halo":x=Math.cos(angle)*rx;y=-ry*.5+Math.sin(angle)*ry*.2;break;
 case "ground":x=Math.cos(angle)*rx;y=ry*.4+Math.sin(angle)*ry*.18;break;
 default:x=Math.sin(i*2.399963)*rx+Math.sin(angle)*rx*.18*sway;y=ry*.5-phase*ry;
 }
 const alpha=Math.sin(phase*Math.PI)*clamp(Number(c.opacity??1),0,1);
 return {x,y,alpha,scale:Math.max(.01,Number(c.scale)||1),graphic:Math.floor((elapsed+i*3)/6)};
}
export function fxDuration(c){return c.type==="image_transform"?(c.transition==="cut"?1:Math.max(1,Math.round(Number(c.duration)||1))):c.type==="scene_fx"?Math.max(1,Math.round(Number(c.life)||0)):c.type==="scene_fx_stop"?Math.max(1,Math.round(Number(c.fade)||0)):1}

export function auraGeometry(c,width=0,height=0){
 const zoom=clamp(Number(c.auraScale??100)/100||0.01,0.01,20);
 const fit=!!c.fitTarget&&width>0&&height>0;
 const x=fit?Math.max(.05,width/110):1,y=fit?Math.max(.05,height/100):1;
 return {...c,rangeX:(Number(c.rangeX)||0)*zoom*x,rangeY:(Number(c.rangeY)||0)*zoom*y,scale:(Number(c.scale)||1)*zoom*(fit?Math.sqrt(x*y):1)};
}
